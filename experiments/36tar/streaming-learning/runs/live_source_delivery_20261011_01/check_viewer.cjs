const root='E:/VIT Model/runs/';
const html=fs.readFileSync(root+'live_source_preflight_20261011_01/viewer.html','utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
const elements={};
